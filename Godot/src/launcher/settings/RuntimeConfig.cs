namespace Refii.Launcher.Core;

public static class RuntimeConfig
{
    public static SortedDictionary<string, string> ReadValues(string configPath)
    {
        var values = new SortedDictionary<string, string>(StringComparer.Ordinal);
        if (!File.Exists(configPath))
        {
            return values;
        }

        string section = string.Empty;
        foreach (string rawLine in File.ReadLines(configPath))
        {
            string line = StripTomlComment(rawLine).Trim();
            if (line.Length == 0)
            {
                continue;
            }

            if (line[0] == '[' && line[^1] == ']')
            {
                section = line.Substring(1, line.Length - 2).Trim().Replace('.', '_');
                continue;
            }

            int equals = line.IndexOf('=');
            if (equals < 0)
            {
                continue;
            }

            string key = line.Substring(0, equals).Trim();
            string value = line[(equals + 1)..].Trim();
            if (key.Length == 0)
            {
                continue;
            }

            if (section.Length != 0)
            {
                key = section + "_" + key;
            }

            string unquoted = UnquoteTomlString(value);
            values[key] = key == "game_data_root"
                ? NormalizeGameDataRootValue(unquoted, configPath)
                : unquoted;
        }

        return values;
    }

    public static bool WriteValues(
        string configPath,
        IReadOnlyDictionary<string, string> values,
        out string error) =>
        WriteValuesForTitle(Refii.Core.Engine_Title.Active, configPath, values, out error);

    /// <summary>
    /// Writes <paramref name="values"/> to <paramref name="configPath"/> filtered strictly to settings
    /// that apply to <paramref name="title"/>, preserving unknown keys while dropping other titles' CVars.
    /// </summary>
    public static bool WriteValuesForTitle(
        Refii.Core.Engine_Title title,
        string configPath,
        IReadOnlyDictionary<string, string> values,
        out string error)
    {
        error = string.Empty;
        try
        {
            string? parent = Path.GetDirectoryName(configPath);
            if (!string.IsNullOrEmpty(parent))
            {
                Directory.CreateDirectory(parent!);
            }

            var builder = new StringBuilder();
            builder.Append("# Runtime config generated by the launcher.\n");
            builder.Append("# Every setting the launcher offers is written explicitly.\n\n");

            // THE TARGET TITLE'S SETTINGS ONLY: each title's file holds what that game reads, and
            // a key of another title's is dropped rather than kept under "Other".
            var written = new HashSet<string>(StringComparer.Ordinal);
            string currentCategory = string.Empty;
            foreach (RuntimeCVarDefinition definition in RuntimeCVarSet.For(title))
            {
                if (!ShouldWriteCVar(definition))
                {
                    continue;
                }

                if (definition.Category != currentCategory)
                {
                    builder.Append('\n').Append("# ").Append(definition.Category).Append('\n');
                    currentCategory = definition.Category;
                }

                string rawValue = values.TryGetValue(definition.Name, out string? existing)
                    ? existing
                    : definition.DefaultValue;

                if (!string.IsNullOrEmpty(definition.Description))
                {
                    builder.Append("# ").Append(definition.Description).Append('\n');
                }

                builder.Append(definition.Name)
                    .Append(" = ")
                    .Append(FormatTomlValue(definition, rawValue))
                    .Append('\n');

                written.Add(definition.Name);
            }

            AppendUnrecognised(builder, values, written);

            File.WriteAllText(configPath, builder.ToString(), new UTF8Encoding(false));
            return true;
        }
        catch (Exception exception)
        {
            error = exception.Message;
            return false;
        }
    }

    /// <summary>
    /// Sets <paramref name="set"/> and removes <paramref name="remove"/> in the file at
    /// <paramref name="configPath"/>, every other line kept byte for byte (<see cref="EditText"/>).
    /// A file that does not exist yet is written whole (<see cref="WriteValues"/>). The file is the
    /// active title's; <see cref="EditValuesForTitle"/> names another.
    /// </summary>
    public static bool EditValues(
        string configPath,
        IReadOnlyDictionary<string, string> set,
        IEnumerable<string> remove,
        out string error) =>
        EditValuesForTitle(Refii.Core.Engine_Title.Active, configPath, set, remove, out error);

    /// <summary>
    /// <see cref="EditValues"/> on the file of <paramref name="title"/>: a new key's description and
    /// format come from that title's table, and a file that does not exist yet is written whole from it.
    /// ONLY WHAT CHANGES IS TOUCHED: a key the file already holds at that value (as <see cref="ReadValues"/>
    /// reads it: `"60"` and `60` are the same 60) keeps its line as written, and a key to remove that the
    /// file does not hold is nothing to do; with nothing left, the file is not opened for writing. Every
    /// writer of a title's file goes through here or through <see cref="EnsureDefaultsForTitle"/>, which
    /// does too, so a launch with nothing changed leaves the file's bytes and time as they were.
    /// </summary>
    public static bool EditValuesForTitle(
        Refii.Core.Engine_Title title,
        string configPath,
        IReadOnlyDictionary<string, string> set,
        IEnumerable<string> remove,
        out string error)
    {
        error = string.Empty;
        if (!File.Exists(configPath))
        {
            SortedDictionary<string, string> values = ReadValues(configPath);
            foreach (var pair in set) values[pair.Key] = pair.Value;
            foreach (string key in remove) values.Remove(key);
            return WriteValuesForTitle(title, configPath, values, out error);
        }

        try
        {
            (Dictionary<string, string> changing, List<string> removing) = StillToDo(ReadValues(configPath), set, remove);
            if (changing.Count == 0 && removing.Count == 0)
            {
                return true;
            }

            string before = File.ReadAllText(configPath);
            string after = EditText(before, changing, removing, title);
            if (after != before)
            {
                File.WriteAllText(configPath, after, new UTF8Encoding(false));
            }

            return true;
        }
        catch (Exception exception)
        {
            error = exception.Message;
            return false;
        }
    }

    /// <summary>
    /// THE FILE IS THE PLAYER'S: only the named keys change. A set key keeps its line's place with
    /// the new value (a later line of the same key, or a dotted key under it, goes: a key is held
    /// once); a key the file lacks goes in before the "# Other" block, else at the end, under its
    /// definition's description; a removed key's line goes, with the line above it when that is its
    /// definition's description. Every other line — order, comments, values, keys of another title
    /// or build — stays as it stands. Keys after a <c>[section]</c> header are not top-level and are
    /// never matched; new keys go in before the first header.
    /// </summary>
    internal static string EditText(string text, IReadOnlyDictionary<string, string> set, IEnumerable<string> remove) =>
        EditText(text, set, remove, Refii.Core.Engine_Title.Active);

    /// <summary><see cref="EditText(string, IReadOnlyDictionary{string, string}, IEnumerable{string})"/> with <paramref name="title"/>'s table.</summary>
    internal static string EditText(
        string text, IReadOnlyDictionary<string, string> set, IEnumerable<string> remove, Refii.Core.Engine_Title title)
    {
        string newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        bool endsWithNewline = text.EndsWith('\n');
        var lines = new List<string>(text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'));
        if (endsWithNewline && lines.Count > 0 && lines[^1].Length == 0)
        {
            lines.RemoveAt(lines.Count - 1);
        }

        var removed = new HashSet<string>(remove, StringComparer.Ordinal);
        var placed = new HashSet<string>(StringComparer.Ordinal);
        var definitions = new Dictionary<string, RuntimeCVarDefinition>(StringComparer.Ordinal);
        foreach (RuntimeCVarDefinition known in RuntimeCVarSet.For(title))
        {
            definitions.TryAdd(known.Name, known);
        }

        RuntimeCVarDefinition? Find(string key) =>
            definitions.TryGetValue(key, out RuntimeCVarDefinition? found) ? found : FindDefinition(key);
        string Formatted(string key, string value) =>
            Find(key) is { } definition ? FormatTomlValue(definition, value) : FormatUnknownValue(value);
        var output = new List<string>(lines.Count + set.Count * 2);
        int firstSection = -1;
        int otherHeader = -1;
        foreach (string line in lines)
        {
            string trimmed = StripTomlComment(line).Trim();
            if (firstSection < 0 && trimmed.Length > 1 && trimmed[0] == '[' && trimmed[^1] == ']')
            {
                firstSection = output.Count;
            }

            if (firstSection < 0 && otherHeader < 0 && line.Trim() == "# Other")
            {
                otherHeader = output.Count;
            }

            int equals = trimmed.IndexOf('=');
            string key = firstSection < 0 && equals > 0 ? trimmed[..equals].Trim() : string.Empty;
            if (key.Length == 0)
            {
                output.Add(line);
                continue;
            }

            if (removed.Contains(key) && !set.ContainsKey(key))
            {
                if (output.Count > 0 && Find(key) is { Description.Length: > 0 } gone &&
                    output[^1].Trim() == "# " + gone.Description)
                {
                    output.RemoveAt(output.Count - 1);
                }

                continue;
            }

            if (set.TryGetValue(key, out string? value))
            {
                if (placed.Add(key))
                {
                    output.Add(key + " = " + Formatted(key, value));
                }

                continue;
            }

            if (ParentIn(key, set))
            {
                continue;
            }

            output.Add(line);
        }

        var added = new List<string>();
        foreach ((string key, string value) in set)
        {
            if (placed.Contains(key))
            {
                continue;
            }

            if (Find(key) is { Description.Length: > 0 } definition)
            {
                added.Add("# " + definition.Description);
            }

            added.Add(key + " = " + Formatted(key, value));
        }

        if (added.Count > 0)
        {
            int at = firstSection >= 0 ? firstSection : otherHeader >= 0 ? otherHeader : output.Count;
            while (at > 0 && at <= output.Count && (firstSection >= 0 || otherHeader >= 0) && output[at - 1].Trim().Length == 0)
            {
                --at;
            }

            output.InsertRange(at, added);
        }

        string result = string.Join(newline, output);
        return endsWithNewline || output.Count == 0 ? result + newline : result;
    }

    /// <summary>Whether a dotted <paramref name="key"/> sits under a key being set (TOML cannot hold both).</summary>
    private static bool ParentIn(string key, IReadOnlyDictionary<string, string> set)
    {
        for (int dot = key.IndexOf('.'); dot > 0; dot = key.IndexOf('.', dot + 1))
        {
            if (set.ContainsKey(key[..dot]))
            {
                return true;
            }
        }

        return false;
    }

    public static bool EnsureDefaults(string configPath, out string error) =>
        EnsureDefaultsForTitle(Refii.Core.Engine_Title.Active, configPath, out error);

    /// <summary>
    /// Ensures <paramref name="configPath"/> exists and carries current default roots and preset upgrades
    /// for <paramref name="title"/>. A file that does not exist yet is written whole from the title's
    /// table; an existing one is EDITED: only the keys the defaults pass changed or removed are
    /// touched (<see cref="EditValues"/>), every other line — another title's keys, unknown keys,
    /// comments, order — stays as it stands. The pass never drops a key it did not mean to.
    /// </summary>
    public static bool EnsureDefaultsForTitle(
        Refii.Core.Engine_Title title, string configPath, out string error)
    {
        error = string.Empty;
        SortedDictionary<string, string> values = ReadValues(configPath);
        var before = new SortedDictionary<string, string>(values, StringComparer.Ordinal);
        bool exists = File.Exists(configPath);
        bool changed = !exists;

        changed |= PopulateDefaultRoots(values, configPath);
        changed |= AdoptFixtureShadowDefault(values);
        changed |= AdoptVolumetricFogAndInteriorFogDefault(values);

        if (!File.Exists(configPath))
        {
            DesktopGraphicsPresets.ApplyInitialPresetOnce(values);
            DetectAndApplyHdrDefaults(values);
        }
        else
        {
            changed |= DesktopGraphicsPresets.Upgrade(values);
        }

        if (!changed)
        {
            return true;
        }

        if (!exists)
        {
            return WriteValuesForTitle(title, configPath, values, out error);
        }

        (Dictionary<string, string> set, List<string> remove) = Changes(before, values);
        return set.Count == 0 && remove.Count == 0 || EditValuesForTitle(title, configPath, set, remove, out error);
    }

    /// <summary>
    /// What of an edit is still to do against the file's <paramref name="current"/> values: the keys of
    /// <paramref name="set"/> the file does not hold at that value, the keys of <paramref name="remove"/> it holds.
    /// </summary>
    internal static (Dictionary<string, string> Set, List<string> Remove) StillToDo(
        IReadOnlyDictionary<string, string> current, IReadOnlyDictionary<string, string> set, IEnumerable<string> remove)
    {
        var changing = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((string key, string value) in set)
        {
            if (!current.TryGetValue(key, out string? held) || held != value)
            {
                changing[key] = value;
            }
        }

        var removing = new List<string>();
        foreach (string key in remove)
        {
            if (current.ContainsKey(key) && !changing.ContainsKey(key))
            {
                removing.Add(key);
            }
        }

        return (changing, removing);
    }

    /// <summary>The keys <paramref name="after"/> sets to a new value, and the keys it no longer holds.</summary>
    internal static (Dictionary<string, string> Set, List<string> Remove) Changes(
        IReadOnlyDictionary<string, string> before, IReadOnlyDictionary<string, string> after)
    {
        var set = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((string key, string value) in after)
        {
            if (!before.TryGetValue(key, out string? was) || was != value)
            {
                set[key] = value;
            }
        }

        var remove = new List<string>();
        foreach (string key in before.Keys)
        {
            if (!after.ContainsKey(key))
            {
                remove.Add(key);
            }
        }

        return (set, remove);
    }

    internal static bool PopulateDefaultRoots(IDictionary<string, string> values, string configPath)
    {
        bool changed = false;
        // The roots are anchored on the shared install root; the host states the running title's
        // data root and the save profile on the command line, which outranks the config.
        string baseRoot = Installer.GetInstallRootPath();
        string configDirectory = Path.GetDirectoryName(configPath) ?? string.Empty;

        foreach ((string key, string legacyDefault) in AssetRelativeRoots)
        {
            // If the config carries a stale absolute path from another machine/drive/build folder
            // that does not exist on disk, clear it so it can be re-resolved to the local install:
            if (values.TryGetValue(key, out string? currentVal) &&
                Path.IsPathRooted(currentVal) &&
                (!Directory.Exists(currentVal) || PointsIntoAnotherInstall(currentVal, baseRoot)))
            {
                values.Remove(key);
            }

            string relative = legacyDefault.Length > AssetsPrefix.Length
                ? legacyDefault[(AssetsPrefix.Length + 1)..]
                : string.Empty;
            string absolute = relative.Length == 0
                ? baseRoot
                : Path.Combine(baseRoot, relative.Replace('/', Path.DirectorySeparatorChar));

            string legacy = key == "game_data_root" && configDirectory.Length != 0
                ? ToGeneric(LauncherPaths.Normalize(Path.Combine(configDirectory, AssetsPrefix)))
                : legacyDefault;

            changed |= UpdateDefaultPath(values, key, legacy, ToGeneric(absolute));
        }

        // THE SAVES ARE NEVER IN THIS FILE: the host states the active save profile as the guest's
        // user_data_root on its command line (HostBridge.Initialize). What earlier launchers wrote
        // here was the pre-split shared folder, never read; it goes.
        if (values.TryGetValue("user_data_root", out string? savedRoot) && IsLegacySaveRoot(savedRoot))
        {
            values.Remove("user_data_root");
            changed = true;
        }

        // ONE CACHE CONTAINER, STATED RATHER THAN DERIVED.
        changed |= UpdateDefaultPath(
            values,
            "cache_root",
            ToGeneric(Path.Combine(Installer.GetInstallRootPath(), "assets", "save", "cache")),
            ToGeneric(Refii.Core.Engine_AppRoot.CacheDirectory));

        return changed;
    }

    private static void DetectAndApplyHdrDefaults(IDictionary<string, string> values)
    {
        (bool isHdr, float peakNits, _) = Native.HdrDisplayDetector.QueryPrimaryDisplay();
        if (isHdr)
        {
            values["hdr_output"] = "true";
            if (OperatingSystem.IsWindows())
            {
                values["rendering_driver"] = "d3d12";
            }
            values["hdr_peak_nits"] = peakNits > 0f ? ((int)MathF.Round(peakNits)).ToString() : "1000";
            values["hdr_reference_nits"] = "200";
        }
        else
        {
            values["hdr_output"] = "false";
            values["hdr_peak_nits"] = "1000";
            values["hdr_reference_nits"] = "200";
        }
    }

    /// <summary>
    /// `placed_light_shadows` went from default false to default true, and this file states
    /// every setting explicitly, so an existing install would hold the old default for ever.
    /// ONE SHOT: `placed_light_shadows_world` arrived in the same change and the write this
    /// triggers adds it, so its absence marks a file from before — a player who turns fixture
    /// shadows off afterwards keeps them off.
    /// </summary>
    private static bool AdoptFixtureShadowDefault(IDictionary<string, string> values)
    {
        if (values.Count == 0 || values.ContainsKey("placed_light_shadows_world"))
        {
            return false;
        }

        values["placed_light_shadows_world"] = "false";
        values["placed_light_shadows"] = "true";
        return true;
    }

    /// <summary>
    /// `interior_fog_scale` was previously defaulted to 0.2 as a workaround for the GDB root
    /// schema prototype inheritance bug (`Fogging` record `0xD3516348` returning 0.0 for unstated
    /// distances). With authentic per-level fog extraction restored, the normalized default is 1.0.
    /// ONE SHOT: `volumetric_fog` arrived in the same change, so its absence in an existing
    /// refii.toml marks a file from before and upgrades an untouched 0.2 to 1.0 once.
    /// </summary>
    private static bool AdoptVolumetricFogAndInteriorFogDefault(IDictionary<string, string> values)
    {
        if (values.Count == 0 || values.ContainsKey("volumetric_fog"))
        {
            return false;
        }

        values["volumetric_fog"] = "true";
        if (values.TryGetValue("interior_fog_scale", out string? scale) &&
            float.TryParse(scale.Trim(), System.Globalization.NumberStyles.Float,
                System.Globalization.CultureInfo.InvariantCulture, out float parsed) &&
            MathF.Abs(parsed - 0.2f) < 1e-4f)
        {
            values["interior_fog_scale"] = "1.0";
        }

        return true;
    }

    /// <summary>
    /// True when an absolute root lives inside a DIFFERENT install of this app.
    /// </summary>
    /// <remarks>
    /// A SECOND INSTALL MADE BY COPYING THE FIRST carries its refii.toml, and these roots are
    /// written absolute, so the copy kept reading and writing the original's assets/save: the
    /// same saves, the same RexNet identity, the same friend list. Two instances on one
    /// machine then had one peer id, and a friend code sent between them was a request to
    /// itself. The tell is a root under a directory that holds our own executable and is not
    /// this one; a root the player pointed somewhere that is not a refii install is kept.
    /// </remarks>
    private static bool PointsIntoAnotherInstall(string value, string baseRoot)
    {
        string normalized = LauncherPaths.Normalize(value);
        string thisInstall = LauncherPaths.Normalize(Path.GetDirectoryName(LauncherPaths.Normalize(baseRoot)) ?? string.Empty);
        if (thisInstall.Length == 0)
        {
            return false;
        }

        for (string? dir = normalized; !string.IsNullOrEmpty(dir); dir = Path.GetDirectoryName(dir))
        {
            if (File.Exists(Path.Combine(dir, Platform.ExecutableName)))
            {
                return !string.Equals(LauncherPaths.Normalize(dir), thisInstall, StringComparison.Ordinal);
            }
        }

        return false;
    }

    private const string AssetsPrefix = "assets";

    private static readonly (string Key, string LegacyDefault)[] AssetRelativeRoots =
    {
        ("game_data_root", "assets"),
    };

    /// <summary>The <c>user_data_root</c> launchers wrote before the save profiles: <c>assets/save</c>, relative or absolute.</summary>
    internal static bool IsLegacySaveRoot(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return false;
        }

        string generic = value.Replace('\\', '/').TrimEnd('/');
        return generic == "assets/save" || generic.EndsWith("/assets/save", StringComparison.Ordinal);
    }


    private static bool UpdateDefaultPath(
        IDictionary<string, string> values,
        string key,
        string legacyDefault,
        string packagedValue)
    {
        bool present = values.TryGetValue(key, out string? current);
        if (!present || string.IsNullOrEmpty(current) || current == legacyDefault)
        {
            if (!present || current != packagedValue)
            {
                values[key] = packagedValue;
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Whether a setting is offered in the panel. Nothing depends on another setting's value
    /// any more: the last such gate was the renderer backend, and there is no renderer to pick.
    /// </summary>
    public static bool ShouldShowCVar(RuntimeCVarDefinition definition)
    {
        // HDR sub-settings are configured via the dedicated HDR Settings modal dialog
        if (definition.Name is "hdr_reference_nits" or "hdr_peak_nits")
        {
            return false;
        }

        // Bookkeeping for the presets, not a choice.
        if (definition.Name is GraphicsPresets.RevisionKey or DesktopGraphicsPresets.RevisionKey)
        {
            return false;
        }

        if (!Refii.AndroidRuntime.AndroidLauncherSettings.Shows(definition.Name))
        {
            return false;
        }

        return ShouldWriteCVar(definition);
    }

    /// <summary>
    /// Whether a setting is written to the title's config — the same question as showing it. A setting
    /// nobody can act on should not sit in the file implying it does something.
    /// </summary>
    public static bool ShouldWriteCVar(RuntimeCVarDefinition definition) =>
        GraphicsPresets.ShouldWrite(definition.Name) &&
        DesktopGraphicsPresets.ShouldWrite(definition.Name) &&
        (!IsRetiredNativeCategory(definition.Category) || IsDisplayCVar(definition.Name));

    /// <summary>The settings panel's name for everything the player tunes about the picture.</summary>
    public const string DisplayCategory = "Display";

    /// <summary>
    /// Categories of SDK settings the embedded game does not use: its window, presenter, GPU,
    /// input and audio. Godot draws, takes input and plays the sound, so none of these is the
    /// path that runs. The guest DOES read this file — the host bridge states the app root — so
    /// they must not be written either: retiring them hides them AND stops them being written,
    /// because `ShouldWriteCVar` is this same predicate.
    /// </summary>
    private static bool IsRetiredNativeCategory(string category) =>
        category is "UI/Window" or "UI/Presenter" or "UI/D3D12"
            or "GPU" or "GPU/Shader" or "GPU/D3D12"
            or "Input" or "Input/Keybinds" or "Audio";

    /// <summary>
    /// The handful of keys inside those categories that the GODOT window still reads, and which
    /// therefore move to <see cref="DisplayCategory"/> rather than being retired with the rest —
    /// see <c>GameWindowSettings.Load</c>. Retiring these would stop them being written and the
    /// game would silently fall back to a default window.
    /// </summary>
    /// <remarks>
    /// `window_width` and `window_height` are deliberately NOT here. They are the old
    /// type-in-a-number pair, replaced by the aspect and resolution dropdowns — retiring them
    /// keeps one answer to "how big is the window" rather than two that can disagree.
    /// </remarks>
    /// <para>`vsync` is not here either: the panel's one VSync switch is `vsync_mode`, which
    /// has an "off" value; <c>GameWindowSettings.Load</c> still reads a false left in a file.</para>
    public static bool IsDisplayCVar(string name) =>
        name is "fullscreen" or "monitor";

    internal static string StripTomlComment(string line)
    {
        bool inString = false;
        bool escaped = false;
        var result = new StringBuilder(line.Length);
        foreach (char ch in line)
        {
            if (escaped)
            {
                result.Append(ch);
                escaped = false;
                continue;
            }

            if (ch == '\\')
            {
                result.Append(ch);
                escaped = true;
                continue;
            }

            if (ch == '"')
            {
                inString = !inString;
                result.Append(ch);
                continue;
            }

            if (ch == '#' && !inString)
            {
                break;
            }

            result.Append(ch);
        }

        return result.ToString();
    }

    internal static string UnquoteTomlString(string value)
    {
        value = value.Trim();
        if (value.Length < 2 || value[0] != '"' || value[^1] != '"')
        {
            return value;
        }

        var result = new StringBuilder(value.Length - 2);
        bool escaped = false;
        for (int i = 1; i < value.Length - 1; i++)
        {
            char ch = value[i];
            if (escaped)
            {
                result.Append(ch switch
                {
                    'n' => '\n',
                    't' => '\t',
                    'r' => '\r',
                    _ => ch,
                });
                escaped = false;
                continue;
            }

            if (ch == '\\')
            {
                escaped = true;
                continue;
            }

            result.Append(ch);
        }

        return result.ToString();
    }

    internal static string EscapeTomlString(string value)
    {
        var result = new StringBuilder(value.Length + 2);
        result.Append('"');
        foreach (char ch in value)
        {
            switch (ch)
            {
                case '\\':
                    result.Append("\\\\");
                    break;
                case '"':
                    result.Append("\\\"");
                    break;
                case '\n':
                    result.Append("\\n");
                    break;
                case '\t':
                    result.Append("\\t");
                    break;
                case '\r':
                    result.Append("\\r");
                    break;
                default:
                    result.Append(ch);
                    break;
            }
        }

        result.Append('"');
        return result.ToString();
    }

    internal static string NormalizeBoolValue(string value)
    {
        value = value.ToLowerInvariant();
        if (value is "1" or "yes" or "on")
        {
            return "true";
        }

        if (value is "0" or "no" or "off")
        {
            return "false";
        }

        return value is "true" or "false" ? value : "false";
    }

    /// <summary>
    /// Writes back every key that has no definition, instead of dropping it.
    /// </summary>
    /// <remarks>
    /// THIS FILE IS THE ONE SETTINGS FILE, so a writer that only knows how to emit the keys it
    /// has definitions for is a writer that deletes everybody else's. That is not hypothetical:
    /// the definitions are generated from the native runtime's own cvars, so anything Godot-side
    /// — the texture pipeline's settings, for one — used to survive exactly until the player next
    /// opened the settings panel and saved. The loss was silent and nothing named the key.
    ///
    /// It also protects the opposite direction: a config written by a NEWER build that knows
    /// cvars this one does not, opened by an older launcher, keeps them rather than being
    /// downgraded on the first save.
    ///
    /// The values are written back the way they came out of <see cref="ReadValues"/>, which
    /// unquoted them, so anything that is not plainly a bool or a number is re-quoted. That
    /// round trips: <see cref="ReadValues"/> unquotes again on the way back in.
    /// </remarks>
    private static void AppendUnrecognised(
        StringBuilder builder,
        IReadOnlyDictionary<string, string> values,
        HashSet<string> written)
    {
        var unrecognised = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach ((string key, string value) in values)
        {
            // A key with a definition that ShouldWriteCVar declined is INTENTIONALLY absent —
            // it belongs to a retired category, or to another title — so only keys with no
            // definition at all belong here.
            if (!written.Contains(key) && FindDefinition(key) is null && !RetiredKeys.Contains(key) &&
                !ClashesWithAValue(key, values, written))
            {
                unrecognised[key] = value;
            }
        }

        if (unrecognised.Count == 0)
        {
            return;
        }

        builder.Append('\n')
            .Append("# Other\n")
            .Append("# Keys this build has no definition for. Preserved verbatim.\n");

        foreach ((string key, string value) in unrecognised)
        {
            builder.Append(key).Append(" = ").Append(FormatUnknownValue(value)).Append('\n');
        }
    }

    /// <summary>
    /// Whether a dotted key is nested under a key that holds a value: <c>key_hotbar.slot0</c> beside
    /// <c>key_hotbar = "..."</c>. TOML can't hold both, and one such line makes the whole file
    /// unreadable to the game, which then starts with none of its settings; the dotted key goes.
    /// </summary>
    private static bool ClashesWithAValue(
        string key, IReadOnlyDictionary<string, string> values, HashSet<string> written)
    {
        for (int dot = key.IndexOf('.'); dot > 0; dot = key.IndexOf('.', dot + 1))
        {
            string parent = key[..dot];
            if (written.Contains(parent) || values.ContainsKey(parent))
            {
                return true;
            }
        }

        return false;
    }

